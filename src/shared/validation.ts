/** Thrown for any IPC payload that does not match its contract. */
export class ValidationError extends Error {
  override name = 'ValidationError'
}

const ID_PATTERN = /^[A-Za-z0-9-]{1,64}$/
/** Imported asset ids are generated by the main process: a UUID plus a whitelisted extension. */
export const ASSET_ID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(png|jpg|webp|gif|mp3|wav|ogg|m4a)$/
const HEX_COLOR = /^#[0-9a-fA-F]{6}$/
const CLOSE_ACTIONS = ['tray', 'quit'] as const satisfies readonly CloseAction[]
const LANGUAGES = ['system', 'zh-CN', 'en'] as const satisfies readonly LanguageSetting[]

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function assertOnlyKeys(value: Record<string, unknown>, allowed: readonly string[], what: string): void {
  for (const key of Object.keys(value)) {
    if (!allowed.includes(key)) throw new ValidationError(`${what}: unexpected field "${key}"`)
  }
}

export function validateId(value: unknown): string {
  if (typeof value !== 'string' || !ID_PATTERN.test(value)) throw new ValidationError('Invalid task id')
  return value
}

function validateTitle(value: unknown): string {
  if (typeof value !== 'string') throw new ValidationError('Title must be a string')
  const title = value.trim()
  if (title.length === 0) throw new ValidationError('Title is required')
  if (title.length > TITLE_MAX_LENGTH) throw new ValidationError('Title is too long')
  return title
}

function validateDescription(value: unknown): string {
  if (value === undefined || value === null) return ''
  if (typeof value !== 'string') throw new ValidationError('Description must be a string')
  const description = value.trim()
  if (description.length > DESCRIPTION_MAX_LENGTH) throw new ValidationError('Description is too long')
  return description
}

function validateTimer(value: unknown): number | null {
  if (value === undefined || value === null) return null
  if (typeof value !== 'number' || !Number.isInteger(value)) throw new ValidationError('Timer must be whole seconds')
  if (value < TIMER_MIN_SEC || value > TIMER_MAX_SEC) throw new ValidationError('Timer is out of range')
  return value
}

function oneOf<T extends string>(value: unknown, options: readonly T[], name: string): T {
  if (typeof value !== 'string' || !options.includes(value as T)) throw new ValidationError(`Unknown ${name}`)
  return value as T
}

function validateThemeOverride(value: unknown): ThemeId | null {
  if (value === undefined || value === null) return null
  return oneOf(value, THEME_IDS, 'theme')
}

export function validateDateKey(value: unknown, name = 'date'): string {
  if (!isDateKey(value)) throw new ValidationError(`${name} must be a YYYY-MM-DD date`)
  return value
}

export function validateRecurrence(value: unknown): RecurrenceRule | null {
  if (value === undefined || value === null) return null
  if (!isPlainObject(value)) throw new ValidationError('Recurrence must be an object')
  assertOnlyKeys(value, ['preset', 'unit', 'interval', 'weekdays', 'startDate', 'endDate'], 'Recurrence')
  const unit = oneOf(value.unit ?? 'day', RECURRENCE_UNITS, 'recurrence unit')
  const weekdays = value.weekdays ?? []
  if (!Array.isArray(weekdays) || weekdays.length > 7) throw new ValidationError('weekdays must be a list')
  const startDate = validateDateKey(value.startDate, 'startDate')
  const endDate = value.endDate === undefined || value.endDate === null ? null : validateDateKey(value.endDate, 'endDate')
  if (endDate !== null && endDate < startDate) throw new ValidationError('endDate is before startDate')
  return normalizeRule({
    preset: oneOf(value.preset, RECURRENCE_PRESETS, 'recurrence preset'),
    unit,
    interval: validateIntInRange(value.interval ?? 1, 1, RECURRENCE_INTERVAL_MAX[unit], 'interval'),
    weekdays: weekdays.map((d: unknown) => validateIntInRange(d, 0, 6, 'weekday')),
    startDate,
    endDate
  })
}

function validateTime(value: unknown, name: string): string {
  if (typeof value !== 'string' || !TIME_PATTERN.test(value)) throw new ValidationError(`${name} must be HH:MM`)
  return value
}

/** A deadline: a date (null for a repeating task, which is due on each occurrence) and an optional time. */
export function validateDue(value: unknown): TaskDue | null {
  if (value === undefined || value === null) return null
  if (!isPlainObject(value)) throw new ValidationError('Due must be an object')
  assertOnlyKeys(value, ['date', 'time'], 'Due')
  return {
    date: value.date === undefined || value.date === null ? null : validateDateKey(value.date, 'due date'),
    time: value.time === undefined || value.time === null ? null : validateTime(value.time, 'due time')
  }
}

export function validateReminderMinutes(value: unknown): number | null {
  if (value === undefined || value === null) return null
  return validateIntInRange(value, 0, REMINDER_MAX_MINUTES, 'reminderMinutes')
}

export function validateReminderSettings(value: unknown): ReminderSettings {
  if (!isPlainObject(value)) throw new ValidationError('Reminder settings must be an object')
  assertOnlyKeys(value, ['enabled', 'defaultMinutes', 'sound', 'allDayTime'], 'Reminder settings')
  if (typeof value.enabled !== 'boolean') throw new ValidationError('enabled must be a boolean')
  if (typeof value.sound !== 'boolean') throw new ValidationError('sound must be a boolean')
  return {
    enabled: value.enabled,
    defaultMinutes: validateReminderMinutes(value.defaultMinutes),
    sound: value.sound,
    allDayTime: validateTime(value.allDayTime, 'allDayTime')
  }
}

/** What `DataStore.createTask` receives: every field present. */
export type ValidTaskInput = Required<TaskInput>

export function validateTaskInput(value: unknown): ValidTaskInput {
  if (!isPlainObject(value)) throw new ValidationError('Task input must be an object')
  assertOnlyKeys(
    value,
    ['title', 'description', 'timerDurationSec', 'themeOverride', 'recurrence', 'due', 'reminderMinutes'],
    'Task input'
  )
  return {
    title: validateTitle(value.title),
    description: validateDescription(value.description),
    timerDurationSec: validateTimer(value.timerDurationSec),
    themeOverride: validateThemeOverride(value.themeOverride),
    recurrence: validateRecurrence(value.recurrence),
    due: validateDue(value.due),
    reminderMinutes: validateReminderMinutes(value.reminderMinutes)
  }
}

export function validateTaskPatch(value: unknown): TaskPatch {
  if (!isPlainObject(value)) throw new ValidationError('Task patch must be an object')
  assertOnlyKeys(
    value,
    ['title', 'description', 'timerDurationSec', 'restartTimer', 'themeOverride', 'recurrence', 'due', 'reminderMinutes'],
    'Task patch'
  )
  const patch: TaskPatch = {}
  if ('title' in value) patch.title = validateTitle(value.title)
  if ('description' in value) patch.description = validateDescription(value.description)
  if ('timerDurationSec' in value) patch.timerDurationSec = validateTimer(value.timerDurationSec)
  if ('restartTimer' in value) {
    if (typeof value.restartTimer !== 'boolean') throw new ValidationError('restartTimer must be a boolean')
    patch.restartTimer = value.restartTimer
  }
  if ('themeOverride' in value) patch.themeOverride = validateThemeOverride(value.themeOverride)
  if ('recurrence' in value) patch.recurrence = validateRecurrence(value.recurrence)
  if ('due' in value) patch.due = validateDue(value.due)
  if ('reminderMinutes' in value) patch.reminderMinutes = validateReminderMinutes(value.reminderMinutes)
  return patch
}

function validateIntInRange(value: unknown, min: number, max: number, name: string): number {
  if (typeof value !== 'number' || !Number.isInteger(value) || value < min || value > max) {
    throw new ValidationError(`${name} must be an integer between ${min} and ${max}`)
  }
  return value
}

function validateAssetId(value: unknown): string | null {
  if (value === null || value === undefined) return null
  if (typeof value !== 'string' || !ASSET_ID_PATTERN.test(value)) throw new ValidationError('Invalid asset id')
  return value
}

export function validateCustomTheme(value: unknown): CustomTheme {
  if (!isPlainObject(value)) throw new ValidationError('Custom theme must be an object')
  const keys = [
    'icon',
    'iconAssetId',
    'accentColor',
    'sound',
    'soundAssetId',
    'animation',
    'position',
    'durationSec',
    'volume'
  ] as const
  assertOnlyKeys(value, keys, 'Custom theme')
  if (typeof value.accentColor !== 'string' || !HEX_COLOR.test(value.accentColor)) {
    throw new ValidationError('accentColor must be #RRGGBB')
  }
  const theme: CustomTheme = {
    icon: oneOf(value.icon, [...BUILTIN_ICONS, 'imported'] as const, 'icon'),
    iconAssetId: validateAssetId(value.iconAssetId),
    accentColor: value.accentColor.toLowerCase(),
    // A saved setting naming a removed sound (the old "Activra Chime") keeps the rest of the theme.
    sound: oneOf(
      typeof value.sound === 'string' ? (RETIRED_SOUNDS[value.sound] ?? value.sound) : value.sound,
      [...BUILTIN_SOUNDS, 'imported', 'none'] as const,
      'sound'
    ),
    soundAssetId: validateAssetId(value.soundAssetId),
    animation: oneOf(value.animation, ANIMATIONS, 'animation'),
    position: oneOf(value.position, POSITIONS, 'position'),
    durationSec: validateIntInRange(
      value.durationSec,
      NOTIFICATION_DURATION_MIN_SEC,
      NOTIFICATION_DURATION_MAX_SEC,
      'durationSec'
    ),
    volume: validateIntInRange(value.volume, 0, 100, 'volume')
  }
  if (theme.icon === 'imported' && !theme.iconAssetId) throw new ValidationError('Imported icon needs an asset')
  if (theme.sound === 'imported' && !theme.soundAssetId) throw new ValidationError('Imported sound needs an asset')
  return theme
}

export function validateWidgetSettings(value: unknown): WidgetSettings {
  if (!isPlainObject(value)) throw new ValidationError('Widget settings must be an object')
  assertOnlyKeys(value, ['visible', 'alwaysOnTop', 'opacity', 'shape', 'animation', 'appearance'], 'Widget settings')
  if (typeof value.visible !== 'boolean') throw new ValidationError('visible must be a boolean')
  if (typeof value.alwaysOnTop !== 'boolean') throw new ValidationError('alwaysOnTop must be a boolean')
  return {
    visible: value.visible,
    alwaysOnTop: value.alwaysOnTop,
    opacity: validateWidgetOpacity(value.opacity),
    shape: oneOf(value.shape, WIDGET_SHAPES, 'widget shape'),
    animation: oneOf(value.animation, WIDGET_ANIMATIONS, 'widget animation'),
    appearance: oneOf(value.appearance, APPEARANCES, 'appearance')
  }
}

export function validateWidgetOpacity(value: unknown): number {
  return validateIntInRange(value, WIDGET_OPACITY_MIN, WIDGET_OPACITY_MAX, 'opacity')
}

export function validateBoolean(value: unknown, name: string): boolean {
  if (typeof value !== 'boolean') throw new ValidationError(`${name} must be a boolean`)
  return value
}

export function validateSettingsPatch(value: unknown): SettingsPatch {
  if (!isPlainObject(value)) throw new ValidationError('Settings patch must be an object')
  assertOnlyKeys(
    value,
    [
      'language',
      'notificationDurationSec',
      'notificationVolume',
      'notificationPosition',
      'achievementTheme',
      'customTheme',
      'closeAction',
      'appearance',
      'widget',
      'reminders',
      'widgetShortcut'
    ],
    'Settings patch'
  )
  const patch: SettingsPatch = {}
  if ('language' in value) {
    patch.language = oneOf(value.language, LANGUAGES, 'language')
  }
  if ('notificationDurationSec' in value) {
    patch.notificationDurationSec = validateIntInRange(
      value.notificationDurationSec,
      NOTIFICATION_DURATION_MIN_SEC,
      NOTIFICATION_DURATION_MAX_SEC,
      'notificationDurationSec'
    )
  }
  if ('notificationVolume' in value) {
    patch.notificationVolume = validateIntInRange(value.notificationVolume, 0, 100, 'notificationVolume')
  }
  if ('notificationPosition' in value) {
    patch.notificationPosition = oneOf(value.notificationPosition, POSITIONS, 'position')
  }
  if ('achievementTheme' in value) patch.achievementTheme = oneOf(value.achievementTheme, THEME_IDS, 'theme')
  if ('customTheme' in value) patch.customTheme = validateCustomTheme(value.customTheme)
  if ('closeAction' in value) patch.closeAction = oneOf(value.closeAction, CLOSE_ACTIONS, 'close action')
  if ('appearance' in value) patch.appearance = oneOf(value.appearance, APPEARANCES, 'appearance')
  if ('widget' in value) patch.widget = validateWidgetSettings(value.widget)
  if ('reminders' in value) patch.reminders = validateReminderSettings(value.reminders)
  if ('widgetShortcut' in value) {
    if (value.widgetShortcut !== null && !isValidAccelerator(value.widgetShortcut)) {
      throw new ValidationError('widgetShortcut must be a shortcut with Ctrl, Alt or Win and one key, or null')
    }
    patch.widgetShortcut = value.widgetShortcut as string | null
  }
  return patch
}
